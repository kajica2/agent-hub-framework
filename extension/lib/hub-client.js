// hub-client.js — Phase 1: PR-based intake (plan §15/§22G). No server needed.
// The extension opens a PR against the hub repo with one markdown file per
// task under channels/captures/YYYY-MM-DD/<task-id>.md. Kai merges; the
// hub loop picks it up. With no token configured, exportLocalBundle() gives
// the popup a download instead — the queue is never a dead end.

const API = 'https://api.github.com';

function b64(s) {
  return btoa(unescape(encodeURIComponent(s)));
}

// One conversation/task = one file, YAML frontmatter + transcript (plan §15).
export function buildTaskFile(task) {
  const t = task.payload || {};
  const fm = [
    '---',
    `id: ${task.id}`,
    `created_at: ${task.created_at}`,
    `kind: ${task.kind}`,
    `helper: ${task.helper}`,
    `priority: ${task.priority}`,
    `status: pending`,
    `source: sovereign-signal-bridge/0.1.0`,
    t.metadata_only ? 'metadata_only: true' : null,
    '---',
  ].filter(Boolean).join('\n');

  const body = [
    `# Capture → ${task.helper}`,
    '',
    t.url ? `- **URL:** ${t.url}` : null,
    t.title ? `- **Title:** ${t.title}` : null,
    t.kind ? `- **Classified as:** ${t.kind}` : null,
    '',
    t.metadata_only
      ? '_Content withheld: source matches the paywall host list._'
      : (t.text ? `## Text\n\n${t.text}` : null),
    t.audio ? `## Audio\n\n_(base64 webm/opus attached as ${task.id}.audio.b64 in the PR commit)_` : null,
    t.html ? `## Page HTML\n\n\`\`\`html\n${String(t.html).slice(0, 50000)}\n\`\`\`` : null,
  ].filter(Boolean).join('\n');

  return `${fm}\n\n${body}\n`;
}

async function gh(token, path, opts = {}) {
  const res = await fetch(`${API}${path}`, {
    ...opts,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github+json',
      'Content-Type': 'application/json',
      'User-Agent': 'sovereign-signal-bridge',
      ...(opts.headers || {}),
    },
    body: opts.body ? JSON.stringify(opts.body) : undefined,
  });
  if (!res.ok) throw new Error(`GitHub API ${opts.method || 'GET'} ${path} → ${res.status}: ${(await res.text()).slice(0, 200)}`);
  return res.json();
}

// Open one PR carrying all queued tasks. Returns { prUrl, branch }.
export async function openPr({ token, repo, base = 'main', tasks }) {
  if (!token) throw new Error('NO_TOKEN: set a GitHub PAT (contents:write) in Settings');
  const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
  const branch = `bridge/captures-${stamp}`;
  const date = new Date().toISOString().slice(0, 10);

  const { object: { sha: baseSha } } = await gh(token, `/repos/${repo}/git/ref/heads/${base}`);
  await gh(token, `/repos/${repo}/git/refs`, { method: 'POST', body: { ref: `refs/heads/${branch}`, sha: baseSha } });

  const entries = tasks.map((t) => ({
    path: `channels/captures/${date}/${t.id}.md`,
    mode: '100644',
    type: 'blob',
    content: b64(buildTaskFile(t)),
  }));
  // Audio blobs ride alongside their task file (still Phase-1-safe: files only).
  for (const t of tasks) {
    if (t.payload?.audio) {
      entries.push({
        path: `channels/captures/${date}/${t.id}.audio.b64`,
        mode: '100644', type: 'blob', content: t.payload.audio,
      });
    }
  }

  const tree = await gh(token, `/repos/${repo}/git/trees`, { method: 'POST', body: { base_tree: baseSha, tree: entries } });
  const commit = await gh(token, `/repos/${repo}/git/commits`, {
    method: 'POST',
    body: { message: `bridge: ${tasks.length} capture task(s) ${date}`, tree: tree.sha, parents: [baseSha] },
  });
  await gh(token, `/repos/${repo}/git/refs/heads/${branch}`, { method: 'PATCH', body: { sha: commit.sha, force: true } });

  const pr = await gh(token, `/repos/${repo}/pulls`, {
    method: 'POST',
    body: {
      title: `bridge: ${tasks.length} capture task(s) from Sovereign Signal Bridge`,
      head: branch, base,
      body: 'Auto-generated by the Sovereign Signal Bridge extension. Merge to feed the hub loop; the loop picks up files under channels/captures/.',
    },
  });
  return { prUrl: pr.html_url, branch };
}

// No-token fallback: a JSON bundle the popup downloads. Same shape the PR files carry.
export function exportLocalBundle(tasks) {
  return JSON.stringify({
    exported_at: new Date().toISOString(),
    generator: 'sovereign-signal-bridge/0.1.0',
    tasks: tasks.map((t) => ({ ...t, file: buildTaskFile(t) })),
  }, null, 2);
}
